const L = require('./lib.js');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  ✓ ' + m); } else { fail++; console.log('  ✗ ' + m); } };
(async () => {
  const b = await L.launch(), docs = L.seed();
  const p = await L.open(b, 'admin', docs, { uid: 'cu_uadmin' });
  await L.view(p, 'theme');
  const sk = await p.evaluate(() => [...document.querySelectorAll('#main .skin')].map((s) => ({ v: s.dataset.v, t: s.innerText.replace(/\n/g, ' ') })));
  ok(sk.length === 7 && sk[0].v === 'haader', 'سمة «حاضر» أول السمات المتاحة، والسمات السابقة باقية: ' + sk.length);
  ok(/أزرق الهوية وأخضر الإنجاز/.test(sk[0].t), 'اسم السمة واضح');
  ok(/هوية المؤسسة العامة للتدريب/.test(await L.text(p)), 'شرح سبب اختيار الأزرق للهوية والأخضر للإنجاز');
  await p.evaluate(() => ACT.skin({ dataset: { v: 'haader' } }));
  await L.flush(p);
  const v = await p.evaluate(() => ({ attr: document.documentElement.getAttribute('data-skin'), saved: A.raw.meta.settings.skin, pri: getComputedStyle(document.documentElement).getPropertyValue('--pri').trim(), teal: getComputedStyle(document.documentElement).getPropertyValue('--teal').trim(), nav: getComputedStyle(document.documentElement).getPropertyValue('--nav').trim() }));
  ok(v.attr === 'haader' && v.saved === 'haader', 'التبديل يُطبَّق ويُحفظ');
  ok(v.pri.toUpperCase() === '#0066CC', 'اللون الرئيسي أزرق الهوية: ' + v.pri);
  ok(v.teal.toUpperCase() === '#1B9E63', 'اللون المميّز أخضر الإنجاز: ' + v.teal);
  ok(/#00(2B57|3366)/i.test(v.nav), 'القائمة بأزرق الهوية الداكن: ' + v.nav);
  await L.view(p, 'home');
  ok((await p.evaluate(() => document.querySelectorAll('#main .hcmd .tile.act').length)) === 10, 'لوحة القيادة تعمل بعد التبديل');
  await p.evaluate(() => ACT.skin({ dataset: { v: 'navy' } }));
  await L.flush(p);
  ok((await p.evaluate(() => A.raw.meta.settings.skin)) === 'navy', 'الرجوع إلى أي سمة أخرى يعمل');
  const errs = p.errs.filter((e) => !/ResizeObserver/.test(e));
  ok(!errs.length, 'لا أخطاء: ' + (errs[0] || '—'));
  await b.close();
  console.log(`\n══ ${pass} ناجح، ${fail} فاشل ══`);
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
